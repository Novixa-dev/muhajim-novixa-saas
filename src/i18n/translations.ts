/**
 * Returns a complete translation table for the requested language.
 * Falls back through: exact pack → related pack → English, so every key
 * is always defined even for languages without a full native pack.
 */
export function getTranslation(langCode: string): TranslationKeys {
  const normalized = (langCode || 'en').split('-')[0].toLowerCase();

  const direct = TRANSLATIONS[normalized];
  const related = !direct && RELATED_FALLBACK[normalized] ? TRANSLATIONS[RELATED_FALLBACK[normalized]] : undefined;

  return {
    ...TRANSLATIONS.en,
    ...(direct || related || {}),
    appName: normalized === 'ar' ? 'مُحجِّم' : (direct || related)?.appName || 'Muhajim',
  };
}
